// Kiểm thử: dán báo cáo target tháng → áp dụng
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");
import { readFileSync, mkdirSync } from "node:fs";
const OUT = "/tmp/ui-shots4"; mkdirSync(OUT, { recursive: true });
const fake = readFileSync(new URL("./fake-supabase.js", import.meta.url), "utf8");
const REPORT = readFileSync(new URL("./sample-target-report.txt", import.meta.url), "utf8");
const errors = [];
const b = await chromium.launch(); const p = await (await b.newContext({ viewport: { width: 1360, height: 900 } })).newPage();
p.on("pageerror", (e) => errors.push("pageerror: " + e.message));
p.on("console", (m) => { if (m.type() === "error" && !/ERR_FAILED/.test(m.text())) errors.push("console: " + m.text() + " @" + JSON.stringify(m.location())); });
await p.route(/fonts\.(googleapis|gstatic)/, (r) => r.abort());
await p.route(/cdn\.jsdelivr\.net\/npm\/@supabase/, (r) => r.fulfill({ contentType: "text/javascript", body: fake }));
await p.route(/functions\/v1\/notify/, (r) => r.fulfill({ contentType: "application/json", body: '{"status":"success","items":[]}' }));
await p.goto("http://localhost:8790/v2/");
await p.fill("#lEmail", "dohung712@gmail.com"); await p.fill("#lPass", "x"); await p.click("#fPass button[type=submit]");
await p.waitForSelector("#app:not([hidden])", { timeout: 30000 });
await p.click("#nav [data-page=admin]"); await p.waitForTimeout(1500); await p.click("#aTabs [data-t=score]"); await p.waitForTimeout(1200);
await p.evaluate(() => { document.querySelector("#imp").open = true; });
await p.fill("#impText", REPORT); await p.click("#impParse"); await p.waitForTimeout(600);
await p.screenshot({ path: OUT + "/preview.png", fullPage: true });
await p.click("#impApply"); await p.waitForTimeout(400); await p.click("#modalBody [data-v=ok]"); await p.waitForTimeout(3000);
console.log("toast:", await p.textContent("#toast"));
await p.screenshot({ path: OUT + "/after.png", fullPage: true });
await p.click('[data-items="1001"]'); await p.waitForTimeout(500); await p.fill("#miWd", "20"); await p.waitForTimeout(200);
await p.screenshot({ path: OUT + "/giaomon.png" }); await p.click("#modalBody [data-v=ok]"); await p.waitForTimeout(1500); console.log("giao:", await p.textContent("#toast"));
await p.click("#nav [data-page=report]"); await p.waitForTimeout(1000); if (await p.$("#rStaff")) { await p.selectOption("#rStaff", "1001"); } await p.waitForTimeout(1500);
console.log("report:", (await p.textContent("#view")).replace(/\s+/g, " ").slice(0, 600));
await p.screenshot({ path: OUT + "/report.png", fullPage: true });
await b.close();
console.log(errors.length ? errors.join("\n") : "no browser errors");
